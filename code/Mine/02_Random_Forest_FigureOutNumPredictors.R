# Calculate the optimal number of predictors for EACH metric AND region!
npred_final <- fit_predtest %>% 
  dplyr::group_by(metric, region) %>% 
  dplyr::filter(OOBmse == min(OOBmse)) %>%
  dplyr::select(metric, region, npred = n) %>%
  dplyr::distinct()

print(npred_final)


# ========================================================
# Plot and save separate MSE and R2 graphs for every region
# ========================================================
if(!dir.exists("figures_manuscript")) dir.create("figures_manuscript")

for(r in regions) {
  r_data <- subset(fit_predtest, region == r)
  r_opt <- subset(npred_final, region == r)
  
  if(nrow(r_data) == 0) next
  
  # 1. Generate and save MSE Plot
  p_mse <- ggplot(r_data, aes(x = n, y = OOBmse)) + 
