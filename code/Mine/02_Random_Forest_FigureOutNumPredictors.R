                                        "mean_dry_down_days" = "Days from Peak\nto No Flow",
                                        "hydro_doy" = "First No-Flow Day\n[climate year]"))) +
    labs(title = paste("Random Forest R2 -", r), 
         subtitle = "Red dashed line indicates the chosen model (minimum MSE)",
         x = "Number of Predictors", 
         y = expression("OOB R"^2 * " [Training gages only]")) +
    theme_bw()
  
  ggsave(file.path("figures_manuscript/Mine2", paste0("RandomForest_R2vNumberPredictors_", gsub(" ", "", r), ".png")),
         plot = p_r2, width = 150, height = 150, units = "mm")
