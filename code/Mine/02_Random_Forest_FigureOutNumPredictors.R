## ========================================================
## Test number of predictors to use in final models (NOW FOR ALL REGIONS)
## ========================================================

for (m in metrics){
  for (r in regions){
    
    # Safely format the region name to match the CSVs
    r_safe <- gsub(" ", "", r, fixed = TRUE)
    
    # Load the specific importance file for this Metric AND Region
    imp_file <- file.path("results/Mine", paste0("01_RandomForest_PreliminaryVariableImportance_", m, "_", r_safe, ".csv"))
    
    # Skip if the file doesn't exist (e.g., if a region was dropped for having < 20 stations)
    if(!file.exists(imp_file)) next
    
    rf_var_importance <- readr::read_csv(imp_file, show_col_types = FALSE)
    
    # Filter the actual dataset to the specific region
    if (r == "National") {
      fit_data_r <- fit_data_in
    } else {
      fit_data_r <- subset(fit_data_in, region == r)
    }
    
    for (n_pred in pred_test_range){
      
      rf_var_predtest <- rf_var_importance %>% dplyr::top_n(n = n_pred, wt = ImpCondPerm)
      
      fit_data_predtest <- fit_data_r %>% 
        subset(Sample == "Train") %>% 
        dplyr::select(all_of(m), all_of(rf_var_predtest$predictor)) %>%  
        subset(complete.cases(.))
      
      names(fit_data_predtest)[names(fit_data_predtest) == m] <- "observed"
      
      set.seed(1)
      rf_recipe <- recipe(observed ~ ., data = fit_data_predtest) %>%
        step_normalize(all_predictors(), -all_outcomes())
      
      rf_wflow <- workflow() %>% add_model(rf_engine) %>% add_recipe(rf_recipe)
      rf_fit <- rf_wflow %>% parsnip::fit(data = fit_data_predtest)
      
      current_result <- tibble::tibble(
        metric = m,
        region = r,          # <--- Now tracking the region!
        n = n_pred,
        OOBmse = extract_fit_engine(rf_fit)$prediction.error,
        OOBr2 = extract_fit_engine(rf_fit)$r.squared
      )
      
      fit_predtest <- dplyr::bind_rows(fit_predtest, current_result)
    }
    print(paste0(m, " - ", r, " predictors complete"))
  }
}

